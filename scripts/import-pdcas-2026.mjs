function toDate(value) {
  if (value === null || value === undefined || value === "") return null;
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  const s = String(value).trim();
  if (/^\d{4}-\d{2}-\d{2}/.test(s)) return s.slice(0, 10);
  const m = s.match(/^([a-z]{3})\/(\d{2})$/i);
  if (m && months[m[1].toLowerCase()])
    return `20${m[2]}-${String(months[m[1].toLowerCase()]).padStart(2, "0")}-01`;
  return null;
}
function scopeOf(raw) {
  if (!raw) return [];
  const direct = scopeAliases[raw.trim()];
  if (direct) return direct;
  const parts = raw.split(/\s+e\s+/).map((p) => p.trim());
  const names = parts.flatMap((p) => scopeAliases[p] ?? []);
  if (names.length !== parts.length && !parts.every((p) => scopeAliases[p]))
    throw new Error(`Âmbito sem mapeamento: ${raw}`);
  return [...new Set(names)];
}

